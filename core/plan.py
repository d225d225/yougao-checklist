def budget_items(subplan: str) -> dict[str, float]:
    """回傳 {項目: 千元}，只列有編列的項目。"""
    row = _BUDGET_ROWS.get(subplan)
    if not row:
        return {}
    return {k: v for k, v in zip(_ITEMS, row) if v}


def budget_total_yuan(subplan: str) -> int:
    """115 年 8–12 月經常門概算（元）。"""
    return int(round(sum(budget_items(subplan).values()) * 1000))


def budget_text(subplan: str) -> str:
    items = budget_items(subplan)
    if not items:
        return "（此子計畫在 115 年 8–12 月經費概算表中無編列經常門）"
    parts = "、".join(f"{k} {v:g} 千元" for k, v in items.items())
    return f"115 年 8–12 月經常門概算共 {sum(items.values()):g} 千元：{parts}。"


